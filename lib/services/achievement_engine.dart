import '../models/achievement_models.dart';

class AchievementEvaluation {
  final List<AchievementProgress> achievements;
  final Map<String, DateTime> unlockedAt;
  final List<AchievementProgress> newlyUnlocked;

  const AchievementEvaluation({
    required this.achievements,
    required this.unlockedAt,
    required this.newlyUnlocked,
  });
}

class AchievementEngine {
  const AchievementEngine();

  AchievementEvaluation evaluate({
    required AchievementMetrics metrics,
    required Map<String, DateTime> persistedUnlocks,
    DateTime? now,
  }) {
    final timestamp = now ?? DateTime.now();
    final unlocks = Map<String, DateTime>.from(persistedUnlocks);
    final newlyUnlocked = <AchievementProgress>[];
    final result = <AchievementProgress>[];

    for (final definition in catalog) {
      final value = metrics.value(definition.metric);
      var unlockedAt = unlocks[definition.id];
      if (unlockedAt == null && value >= definition.targetValue) {
        unlockedAt = timestamp;
        unlocks[definition.id] = timestamp;
      }
      final state = unlockedAt != null
          ? AchievementState.unlocked
          : value > 0
          ? AchievementState.inProgress
          : AchievementState.locked;
      final progress = AchievementProgress(
        definition: definition,
        currentValue: value,
        state: state,
        unlockedAt: unlockedAt,
      );
      result.add(progress);
      if (unlockedAt == timestamp &&
          !persistedUnlocks.containsKey(definition.id)) {
        newlyUnlocked.add(progress);
      }
    }
    return AchievementEvaluation(
      achievements: result,
      unlockedAt: unlocks,
      newlyUnlocked: newlyUnlocked,
    );
  }

